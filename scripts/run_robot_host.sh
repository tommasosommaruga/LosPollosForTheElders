#!/usr/bin/env bash
# Pull-and-run entrypoint for the PC connected to Reachy (+ optional Maker Arm).
# Starts Medicine Buddy API on localhost and writes conversation-app env for this checkout.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
APP="$ROOT/apps/medicine_buddy"
PORT="${MEDICINE_BUDDY_PORT:-8787}"
HOST="${MEDICINE_BUDDY_HOST:-127.0.0.1}"
ENV_FILE="$ROOT/integrations/reachy_conversation/.env.generated"

cd "$APP"
if [[ ! -d .venv ]]; then
  echo "No venv yet — running bootstrap..."
  "$ROOT/scripts/bootstrap.sh"
fi
# shellcheck disable=SC1091
source .venv/bin/activate

TOOLS_DIR="$ROOT/integrations/reachy_conversation/external_tools"
PROFILES_DIR="$ROOT/integrations/reachy_conversation/external_profiles"
API_URL="http://${HOST}:${PORT}"
if [[ "$HOST" == "0.0.0.0" ]]; then
  API_URL="http://127.0.0.1:${PORT}"
fi

cat > "$ENV_FILE" <<EOF
# Generated by scripts/run_robot_host.sh — point reachy_mini_conversation_app at this file
# or copy these lines into that app's .env
MEDICINE_BUDDY_URL=${API_URL}
REACHY_MINI_EXTERNAL_TOOLS_DIRECTORY=${TOOLS_DIR}
REACHY_MINI_EXTERNAL_PROFILES_DIRECTORY=${PROFILES_DIR}
REACHY_MINI_CUSTOM_PROFILE=medicine_caregiver
AUTOLOAD_EXTERNAL_TOOLS=1
EOF

echo "Wrote conversation env → $ENV_FILE"
echo ""
echo "Medicine Buddy API starting on ${HOST}:${PORT} (Ctrl+C to stop)"
echo "On the same machine, start pollen conversation with:"
echo "  set -a && source $ENV_FILE && set +a && reachy-mini-conversation-app"
echo "(or merge $ENV_FILE into the conversation app .env once)"
echo ""

exec medicine-buddy serve --host "$HOST" --port "$PORT" --dry-run
